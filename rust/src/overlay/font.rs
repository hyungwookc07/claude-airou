/// The 8×8 bitmap for `character`; anything outside printable ASCII renders as `?`
/// (per the overlay spec: "non-ASCII replaced with '?'").
pub fn glyph(character: char) -> &'static [u8; 8] {
    let code = character as usize;
    if (FIRST_CHAR..LAST_CHAR).contains(&code) {
        &FONT8X8_BASIC[code - FIRST_CHAR]
    } else {
        &FONT8X8_BASIC['?' as usize - FIRST_CHAR]
    }
}

/// Is pixel (x, y) of the glyph set? Row byte per y; bit 0 = leftmost pixel.
pub fn glyph_pixel(bitmap: &[u8; 8], x: usize, y: usize) -> bool {
    if x >= GLYPH_WIDTH || y >= GLYPH_HEIGHT {
        return false;
    }
    (bitmap[y] >> x) & 1 == 1
}

#[cfg(test)]
mod tests {
    use super::*;

    fn render(character: char) -> Vec<String> {
        let bitmap = glyph(character);
        (0..GLYPH_HEIGHT)
            .map(|y| {
                (0..GLYPH_WIDTH)
                    .map(|x| if glyph_pixel(bitmap, x, y) { '#' } else { '.' })
                    .collect()
            })
            .collect()
    }

    #[test]
    fn space_is_blank_and_letters_are_not() {
        assert!(glyph(' ').iter().all(|&row| row == 0));
        assert!(glyph('A').iter().any(|&row| row != 0));
        assert!(glyph('z').iter().any(|&row| row != 0));
        assert!(glyph('0').iter().any(|&row| row != 0));
    }

    #[test]
    fn non_ascii_and_control_fall_back_to_question_mark() {
        assert_eq!(glyph('♥'), glyph('?'));
        assert_eq!(glyph('한'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
        assert_eq!(glyph('\u{7F}'), glyph('?')); // DEL is outside the printable range
    }

    #[test]
    fn exclamation_mark_shape_matches_font8x8() {
        // 0x18 = bits 3,4 set -> pixels at x=3 and x=4.
        assert_eq!(
            render('!'),
            vec!["...##...", "..####..", "..####..", "...##...", "...##...", "........", "...##...", "........"]
        );
    }

    #[test]
    fn glyph_pixel_bounds() {
        let bitmap = glyph('#');
        assert!(!glyph_pixel(bitmap, 8, 0));
        assert!(!glyph_pixel(bitmap, 0, 8));
    }
}
